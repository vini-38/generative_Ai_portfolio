import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense,Flatten
from tensorflow.keras.datasets import mnist
from tensorflow.keras.losses import BinaryCrossentropy
from tensorflow.keras.optimizers import Adam
import matplotlib
import numpy as np

(x_train,y_train),(x_test,y_test)=mnist.load_data()
x_train=(x_train-127.5)/127.5
print(x_train.shape[0])
print(x_train.shape[1:])

generator=Sequential([tf.keras.Input(shape=(100,)),
                      Dense(256,activation="relu"),
                      Dense(512,activation="relu"),
                      Dense(784,activation="tanh"),tf.keras.layers.Reshape((28,28))])

discriminator=Sequential([tf.keras.Input(shape=(28,28)),Flatten(),
                        Dense(256,activation="relu"),
                        Dense(128,activation="relu"),
                        Dense(1,activation="sigmoid")])
discriminator.summary()

cross_entropy=BinaryCrossentropy()
generator_optimizer=Adam()
discriminator_optimizer=Adam()

batch_size = 128

train_dataset = tf.data.Dataset.from_tensor_slices(x_train)
train_dataset = train_dataset.shuffle(60000)
train_dataset = train_dataset.batch(batch_size, drop_remainder=True)
train_dataset = train_dataset.prefetch(tf.data.AUTOTUNE)

epochs = 5

for epoch in range(epochs):
    total_generator_loss = 0.0
    total_discriminator_loss = 0.0
    batch_count = 0

    for real_images in train_dataset:
        current_batch_size = tf.shape(real_images)[0]

        noise = tf.random.normal([current_batch_size, 100])
        fake_images = generator(noise, training=True)

        with tf.GradientTape() as tape:
            real_predictions = discriminator(real_images, training=True)
            fake_predictions = discriminator(
                tf.stop_gradient(fake_images),
                training=True
            )

            real_loss = cross_entropy(
                tf.ones_like(real_predictions),
                real_predictions
            )

            fake_loss = cross_entropy(
                tf.zeros_like(fake_predictions),
                fake_predictions
            )

            discriminator_loss = real_loss + fake_loss

        discriminator_gradients = tape.gradient(
            discriminator_loss,
            discriminator.trainable_variables
        )

        discriminator_optimizer.apply_gradients(
            zip(
                discriminator_gradients,
                discriminator.trainable_variables
            )
        )

        noise = tf.random.normal([current_batch_size, 100])

        with tf.GradientTape() as tape:
            generated_images = generator(noise, training=True)
            predictions = discriminator(generated_images, training=False)

            generator_loss = cross_entropy(
                tf.ones_like(predictions),
                predictions
            )

        generator_gradients = tape.gradient(
            generator_loss,
            generator.trainable_variables
        )

        generator_optimizer.apply_gradients(
            zip(
                generator_gradients,
                generator.trainable_variables
            )
        )

        total_generator_loss += generator_loss
        total_discriminator_loss += discriminator_loss
        batch_count += 1

    avg_generator_loss = total_generator_loss / batch_count
    avg_discriminator_loss = total_discriminator_loss / batch_count

    print(
        f"Epoch {epoch + 1}/{epochs} | "
        f"Generator Loss: {float(avg_generator_loss):.4f} | "
        f"Discriminator Loss: {float(avg_discriminator_loss):.4f}"
    )

